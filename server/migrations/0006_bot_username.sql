-- 0006_bot_username.sql — какой бот подключён к магазину.
--
-- Нужно для двух вещей. Первая: не дать подключить одного бота к двум
-- магазинам. Такой бот на опросе даёт вечный 409 Conflict обоим, а на вебхуке
-- ещё хуже — адрес перезаписывается, и заказы одного магазина начинают
-- приходить в другой. Второе: показать продавцу в админке, какой бот у него
-- сейчас, не расшифровывая токен ради одного имени.
--
-- UNIQUE допускает несколько NULL, поэтому магазины без бота не мешают
-- друг другу.

ALTER TABLE shops ADD COLUMN bot_username VARCHAR(64) NULL
  COMMENT 'username подключённого бота, без @; NULL — бот не подключён'
  AFTER bot_token_enc;

CREATE UNIQUE INDEX uq_shops_bot_username ON shops (bot_username);
