-- 0005_invoice_autonumber.sql — номер счёта берётся из автоинкремента.
--
-- Было: inv_id считался как SELECT MAX(inv_id)+1. Обычный SELECT в InnoDB при
-- REPEATABLE READ ничего не блокирует, поэтому два продавца, нажавшие
-- «Оплатить» одновременно, получали один номер; спасал UNIQUE-индекс, но
-- грубо — второму прилетала ошибка вместо ссылки на оплату. Попытка сделать
-- чтение и вставку одним INSERT ... SELECT убрала дубликаты, но принесла
-- дедлоки: запрос берёт gap-локи по той же таблице, в которую пишет.
--
-- Стало: inv_id = id, то есть значение автоинкремента. Уникальность гарантирует
-- сама СУБД, конкуренции за максимум больше нет. Колонка становится NULL-able
-- только на время вставки: строка создаётся с NULL, следом в той же транзакции
-- проставляется id. UNIQUE в MySQL допускает несколько NULL, поэтому
-- промежуточное состояние конфликтов не создаёт.

ALTER TABLE invoices MODIFY COLUMN inv_id BIGINT UNSIGNED NULL
  COMMENT 'номер счёта, он же InvId в Robokassa; равен id';

UPDATE invoices SET inv_id = id WHERE inv_id IS NULL OR inv_id <> id;
