-- 0004_session_key.sql — отдельный ключ подписи сессий у каждого магазина.
--
-- Раньше билеты админки подписывались на admin_token_hash: ключ подписи
-- совпадал с проверочным хэшем пароля. Дамп базы (бэкап, реплика, украденный
-- снимок диска) давал возможность выписать себе действующий билет в любую
-- админку, вообще не подбирая пароль. Теперь ключ отдельный и случайный,
-- знание хэша пароля больше ничего не даёт.
--
-- Колонка NULL-able намеренно: у магазинов, заведённых до этой миграции,
-- ключа ещё нет, и код откатывается на старое поведение до первого входа
-- (см. buildTenantFromRow и ensureSessionKey в index.js). Так обновление
-- не разлогинивает всех разом.

ALTER TABLE shops ADD COLUMN session_key CHAR(64) NULL
  COMMENT 'ключ подписи билетов админки, hex(32 байта); NULL — магазин до 0004'
  AFTER admin_token_hash;
